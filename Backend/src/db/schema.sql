SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS corrective_actions;
DROP TABLE IF EXISTS post_incident_reports;
DROP TABLE IF EXISTS timeline_events;
DROP TABLE IF EXISTS incidents;
DROP TABLE IF EXISTS deployments;
DROP TABLE IF EXISTS service_dependencies;
DROP TABLE IF EXISTS services;
DROP TABLE IF EXISTS users;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('ADMIN', 'ENGINEER') NOT NULL DEFAULT 'ENGINEER',
  title VARCHAR(100),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE services (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  slug VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(255),
  status ENUM('HEALTHY', 'DEGRADED', 'UNAVAILABLE') NOT NULL DEFAULT 'HEALTHY',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE service_dependencies (
  id INT AUTO_INCREMENT PRIMARY KEY,
  service_id INT NOT NULL,
  depends_on_id INT NOT NULL,
  UNIQUE KEY unique_dependency (service_id, depends_on_id),
  FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE CASCADE,
  FOREIGN KEY (depends_on_id) REFERENCES services(id) ON DELETE CASCADE
);

CREATE TABLE deployments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  version VARCHAR(50) NOT NULL,
  environment VARCHAR(50) NOT NULL DEFAULT 'production',
  status VARCHAR(50) NOT NULL DEFAULT 'SUCCESS',
  description TEXT,
  service_id INT NOT NULL,
  deployed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE CASCADE
);

CREATE TABLE incidents (
  id INT AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  category VARCHAR(100) NOT NULL DEFAULT 'Backend',
  severity ENUM('CRITICAL', 'HIGH', 'MEDIUM', 'LOW') NOT NULL DEFAULT 'MEDIUM',
  status ENUM('OPEN', 'INVESTIGATING', 'MONITORING', 'RESOLVED') NOT NULL DEFAULT 'OPEN',
  service_id INT NOT NULL,
  created_by_id INT NOT NULL,
  assigned_to_id INT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  resolved_at TIMESTAMP NULL,
  FOREIGN KEY (service_id) REFERENCES services(id),
  FOREIGN KEY (created_by_id) REFERENCES users(id),
  FOREIGN KEY (assigned_to_id) REFERENCES users(id)
);

CREATE TABLE timeline_events (
  id INT AUTO_INCREMENT PRIMARY KEY,
  incident_id INT NOT NULL,
  user_id INT NULL,
  type ENUM(
    'INCIDENT_CREATED',
    'STATUS_CHANGE',
    'ASSIGNMENT',
    'COMMENT',
    'NOTE',
    'ERROR_EVENT',
    'SERVER_EVENT',
    'APP_EVENT',
    'DEPLOYMENT_DETECTED',
    'RECOVERY_ACTION'
  ) NOT NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  metadata JSON NULL,
  idempotency_key VARCHAR(120) UNIQUE NULL,
  occurred_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (incident_id) REFERENCES incidents(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE post_incident_reports (
  id INT AUTO_INCREMENT PRIMARY KEY,
  incident_id INT NOT NULL UNIQUE,
  summary TEXT NOT NULL,
  impact TEXT NOT NULL,
  suspected_cause TEXT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (incident_id) REFERENCES incidents(id) ON DELETE CASCADE
);

CREATE TABLE corrective_actions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  incident_id INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  status ENUM('PENDING', 'IN_PROGRESS', 'COMPLETED') NOT NULL DEFAULT 'PENDING',
  assignee_id INT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (incident_id) REFERENCES incidents(id) ON DELETE CASCADE,
  FOREIGN KEY (assignee_id) REFERENCES users(id) ON DELETE SET NULL
);